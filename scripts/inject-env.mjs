import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Setup __dirname for ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// ⚠️ IMPORTANT: Paste your actual Cloudflare Worker URL here.
// This is used when building on GitHub Actions (where .env is not present).
const FALLBACK_WORKER_URL = 'https://your-worker-name.your-subdomain.workers.dev';

console.log('⚙️  Injecting environment variables...');

let envData = {};
const envPath = path.join(rootDir, '.env');

// 1. Try to read local .env file
if (fs.existsSync(envPath)) {
  console.log('✅ Found local .env file. Parsing variables...');
  const envContent = fs.readFileSync(envPath, 'utf8');
  
  envContent.split(/\r?\n/).forEach((line) => {
    // Ignore comments and empty lines
    if (!line || line.trim().startsWith('#')) return;
    
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      const key = match[1];
      let value = match[2] || '';
      // Remove surrounding quotes if present
      value = value.replace(/^['"](.*)['"]$/, '$1');
      envData[key] = value;
    }
  });
} else {
  // 2. Fallback for GitHub Actions (No .env file)
  console.log('⚠️  No .env file found. Using fallback Cloudflare Worker URL.');
  envData['WORKER_URL'] = FALLBACK_WORKER_URL;
}

// 3. Define the output directory (src/generated)
const outputDir = path.join(rootDir, 'src', 'generated');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// 4. Generate the environment file for the app
const outputPath = path.join(outputDir, 'env.js');
const fileContent = `// This file is auto-generated by scripts/inject-env.mjs. Do not edit directly.
export const env = ${JSON.stringify(envData, null, 2)};
`;

fs.writeFileSync(outputPath, fileContent, 'utf8');
console.log(`✅ Successfully generated ${outputPath}`);
console.log('🚀 Environment injection complete.');