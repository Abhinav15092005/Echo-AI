import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Setup __dirname for ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

console.log('⚙️  Injecting environment variables...');

let envData = {};

// 1. Default Fallbacks (Used if not in .env)
const defaults = {
  WORKER_URL: 'https://your-worker-name.your-subdomain.workers.dev', // <-- CHANGE THIS to your real Worker URL
  PRIMARY_MODEL: 'openai/gpt-oss-120b',
  FALLBACK_MODEL: 'llama3-8b-8192' // Add any other models you use
};

const envPath = path.join(rootDir, '.env');

// 2. Try to read local .env file
if (fs.existsSync(envPath)) {
  console.log('✅ Found local .env file. Parsing variables...');
  const envContent = fs.readFileSync(envPath, 'utf8');
  
  envContent.split(/\r?\n/).forEach((line) => {
    if (!line || line.trim().startsWith('#')) return;
    const match = line.match(/^\s*([\w.-]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      const key = match[1];
      let value = match[2] || '';
      value = value.replace(/^['"](.*)['"]$/, '$1'); // strip quotes
      envData[key] = value;
    }
  });
} else {
  console.log('⚠️  No .env file found. Using fallback variables for CI build.');
}

// 3. Merge defaults with .env data (.env overrides defaults)
const finalEnv = { ...defaults, ...envData };

// 4. Generate the environment file
const outputDir = path.join(rootDir, 'src', 'generated');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

const outputPath = path.join(outputDir, 'env.js');

// Create direct exports (e.g., export const WORKER_URL = "...";)
let fileContent = `// This file is auto-generated by scripts/inject-env.mjs. Do not edit directly.\n\n`;
for (const [key, value] of Object.entries(finalEnv)) {
  // Escape any quotes in the value
  const safeValue = JSON.stringify(value);
  fileContent += `export const ${key} = ${safeValue};\n`;
}

fs.writeFileSync(outputPath, fileContent, 'utf8');
console.log(`✅ Successfully generated ${outputPath}`);
console.log('🚀 Environment injection complete.');